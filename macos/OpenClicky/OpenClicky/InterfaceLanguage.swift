    /// Tests set this. Nil follows this Mac, and Clicky when Clicky is set to Chinese.
    static var forcedChinese: Bool?

    static var isChinese: Bool {
        if let forcedChinese { return forcedChinese }
        if Locale.preferredLanguages.contains(where: { $0.hasPrefix("zh") }) { return true }
        return ReplyLanguage.normalizedCode(OpenClickyConfiguration.settings.language) == "zh"
    }

    static func t(_ english: String) -> String {
        guard isChinese else { return english }
        if let translated = table[english], !translated.isEmpty { return translated }
        if let count = settingsCount(in: english) { return "\(count) 项设置" }
        return english
    }

    /// "12 settings" on a folded group.
    private static func settingsCount(in english: String) -> Int? {
        guard english.hasSuffix(" settings") else { return nil }
        return Int(english.dropLast(" settings".count))
    }

