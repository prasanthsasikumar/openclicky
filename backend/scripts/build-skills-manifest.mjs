#!/usr/bin/env node
// Generate backend/src/skillsManifest.ts from ../skills/*/SKILL.md (agent skills: workflow/capability)
// and ../app-skills/*/SKILL.md (app-teaching skills, matched to the frontmost app/site by the mac app)
// so the backend (which has no filesystem on Cloudflare Workers) can serve GET /skills/library.
// Runs on `prebuild` / `pretest`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const skillsDir = path.resolve(here, "..", "..", "skills");
const appSkillsDir = path.resolve(here, "..", "..", "app-skills");
const outFile = path.resolve(here, "..", "src", "skillsManifest.ts");

function frontmatter(md) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md.replace(/^\uFEFF/, ""));
  const out = {};
  if (!m) return out;
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if (!/^["']/.test(v)) v = v.replace(/\s+#.*$/, "").trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    out[kv[1]] = v;
  }
  return out;
}

/** Inline YAML list: `[a, "b"]` → ["a", "b"]; a bare scalar becomes a one-item list. */
function list(v) {
  if (!v) return [];
  const m = /^\[([^\]]*)\]/.exec(v.trim());
  const inner = m ? m[1] : v.trim();
  return inner.split(",").map((s) => s.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
}

function listFiles(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...listFiles(p, base));
    else out.push(path.relative(base, p));
  }
  return out.sort();
}

const skills = [];
function scan(dir, kindOf) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    const skillMd = path.join(dir, e.name, "SKILL.md");
    if (!fs.existsSync(skillMd)) continue;
    const fm = frontmatter(fs.readFileSync(skillMd, "utf8"));
    const entry = {
      id: e.name,
      name: fm.name ?? e.name,
      description: fm.description ?? "",
      kind: kindOf(e.name),
      files: listFiles(path.join(dir, e.name)),
    };
    if (entry.kind === "app") {
      entry.apps = list(fm.apps);
      entry.sites = list(fm.sites);
      entry.surfaces = fm.surfaces ? list(fm.surfaces) : ["talk", "agent"];
    }
    skills.push(entry);
  }
}
scan(skillsDir, (name) => (name.startsWith("openclicky-") ? "workflow" : "capability"));
scan(appSkillsDir, () => "app");
skills.sort((a, b) => a.id.localeCompare(b.id));

const body = `// GENERATED by scripts/build-skills-manifest.mjs — do not edit. Sources: ../../skills/*/SKILL.md (agent skills) and ../../app-skills/*/SKILL.md (app-teaching skills)
export interface SkillManifestEntry {
  id: string;
  name: string;
  description: string;
  kind: "workflow" | "capability" | "app";
  files: string[];
  /** App-teaching skills only: bundle identifiers, browser host suffixes, prompt surfaces. */
  apps?: string[];
  sites?: string[];
  surfaces?: string[];
}

export const SKILLS_MANIFEST: SkillManifestEntry[] = ${JSON.stringify(skills, null, 2)};
`;
fs.writeFileSync(outFile, body);
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${skills.length} skills)`);
