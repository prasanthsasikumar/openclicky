#!/usr/bin/env node
// Generate backend/src/skillsManifest.ts from ../skills/*/SKILL.md so the backend (which has no
// filesystem on Cloudflare Workers) can serve GET /skills/library. Runs on `prebuild` / `pretest`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const skillsDir = path.resolve(here, "..", "..", "skills");
const outFile = path.resolve(here, "..", "src", "skillsManifest.ts");

function frontmatter(md) {
  const m = /^---\n([\s\S]*?)\n---/.exec(md);
  const out = {};
  if (!m) return out;
  for (const line of m[1].split("\n")) {
    const kv = /^([A-Za-z_]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    let v = kv[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    out[kv[1]] = v;
  }
  return out;
}

function listFiles(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...listFiles(p, base));
    else out.push(path.relative(base, p));
  }
  return out.sort();
}

const skills = [];
for (const e of fs.readdirSync(skillsDir, { withFileTypes: true })) {
  if (!e.isDirectory()) continue;
  const skillMd = path.join(skillsDir, e.name, "SKILL.md");
  if (!fs.existsSync(skillMd)) continue;
  const fm = frontmatter(fs.readFileSync(skillMd, "utf8"));
  skills.push({
    id: e.name,
    name: fm.name ?? e.name,
    description: fm.description ?? "",
    kind: e.name.startsWith("openclicky-") ? "workflow" : "capability",
    files: listFiles(path.join(skillsDir, e.name)),
  });
}
skills.sort((a, b) => a.id.localeCompare(b.id));

const body = `// GENERATED by scripts/build-skills-manifest.mjs — do not edit. Source: ../../skills/*/SKILL.md
export interface SkillManifestEntry {
  id: string;
  name: string;
  description: string;
  kind: "workflow" | "capability";
  files: string[];
}

export const SKILLS_MANIFEST: SkillManifestEntry[] = ${JSON.stringify(skills, null, 2)};
`;
fs.writeFileSync(outFile, body);
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${skills.length} skills)`);
